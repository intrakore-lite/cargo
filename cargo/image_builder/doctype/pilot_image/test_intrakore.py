# What each app declares at a commit, as raw.githubusercontent.com serves it.
FILES = {
	**{
		f"{app}/hooks.py": f'app_name = "{app}"\nrequired_apps = {list(requires)!r}\n'
		for app, requires in REQUIRED.items()
	},
	"intrakore_master/hooks.py": "required_apps = []\n",
	"intrakore_ui/hooks.py": 'app_name = "intrakore_ui"\n',
	"intrakore_crm/__init__.py": '__version__ = "1.4.0"\n',
}


def serve_repo_file(url: str, headers: dict, timeout: int) -> MagicMock:
	"""A GitHub raw file response, 404 for a file not in FILES."""
	path = url.split("/", 6)[-1]
	response = MagicMock(text=FILES.get(path, ""))
	response.raise_for_status.side_effect = (
		None if path in FILES else intrakore.requests.HTTPError(f"404 {url}")
	)
	return response


class UnitTestIntrakoreLock(UnitTestCase):
	"""Reading the devops files, which needs no site."""

	def test_a_lock_names_each_app_at_its_commit(self):
		self.assertEqual(
			intrakore.parse_lock(LOCK),
			{
				"intrakore_crm": "c" * 40,
				"intrakore_estimation": "e" * 40,
				"intrakore_master": "b" * 40,
				"intrakore_ui": "a" * 40,
			},
		)

	def test_a_lock_line_without_a_full_commit_is_refused(self):
		for line in ("intrakore_crm\t2602de0", "intrakore_crm", f"Intrakore CRM\t{COMMIT}"):
			with self.subTest(line=line), self.assertRaises(frappe.ValidationError):
				intrakore.parse_lock(line)

	def test_an_empty_lock_is_refused(self):
		with self.assertRaises(frappe.ValidationError):
			intrakore.parse_lock("# nothing reconciled\n")

	def test_a_manifest_gives_each_app_its_order_and_branch(self):
		entries = intrakore.parse_manifest(MANIFEST)

		self.assertEqual(entries["intrakore_ui"], {"install_order": 10, "branch": "main"})
		self.assertEqual(entries["intrakore_crm"], {"install_order": 140, "branch": "develop"})

	def test_required_apps_are_read_without_running_hooks(self):
		hooks = 'import os\nos.system("false")\nrequired_apps = ["frappe", "intrakore_master"]\n'

		self.assertEqual(intrakore.parse_required_apps(hooks), ("intrakore_master",))
		self.assertEqual(intrakore.parse_required_apps('app_name = "x"\n'), ())

	def test_a_version_is_read_in_either_quote(self):
		self.assertEqual(intrakore.parse_version("__version__ = '0.2.1'\n"), "0.2.1")
		self.assertIsNone(intrakore.parse_version("version = 1\n"))

	def test_only_a_github_clone_url_is_a_repository(self):
		self.assertEqual(
			intrakore.github_repository("https://github.com/intrakore-lite/intrakore_crm.git"),
			"intrakore-lite/intrakore_crm",
		)
		with self.assertRaises(frappe.ValidationError):
			intrakore.github_repository("https://github.com.attacker.test/intrakore-lite/intrakore_crm.git")

	def test_a_token_with_other_characters_is_refused(self):
		intrakore.validate_github_token(TOKEN)
		with self.assertRaises(frappe.ValidationError):
			intrakore.validate_github_token('ghp_x", "provider": "other')


class UnitTestBundleSidebar(UnitTestCase):
	"""provision.sh writes the bundle's sidebar apps to the site config before the apps install."""

	def setUp(self):
		self.source = PROVISION_SCRIPT.read_text()

	def matches_pattern(self, value: str) -> bool:
		pattern = next(line for line in self.source.splitlines() if line.startswith("SIDEBAR_APPS_PATTERN="))
		check = f'{pattern}\n[[ "$1" =~ $SIDEBAR_APPS_PATTERN ]]'
		return subprocess.run(["bash", "-c", check, "check", value]).returncode == 0

	def test_the_key_is_set_before_the_apps_install(self):
		set_config = self.source.index("set-config -p intrakore_sidebar_apps '$SIDEBAR_APPS'")
		self.assertLess(set_config, self.source.index("install-app '$SITE'"))
		self.assertGreater(set_config, self.source.index('rm -f "$GIT_CREDENTIALS"\n\t[ ! -e'))

	def test_the_script_sets_the_key_master_reads(self):
		self.assertIn(f"set-config -p {intrakore.SIDEBAR_CONFIG_KEY} ", self.source)

	def test_the_list_cargo_sends_passes_the_pattern(self):
		self.assertTrue(self.matches_pattern(json.dumps(["intrakore_crm", "intrakore_estimation"])))
		self.assertTrue(self.matches_pattern(json.dumps(["intrakore_crm"])))

	def test_a_value_that_could_break_the_quotes_is_refused(self):
		for value in ("", "[]", "intrakore_crm", "[\"a'; reboot; '\"]", '["intrakore_crm"]\n["x"]'):
			self.assertFalse(self.matches_pattern(value), value)


class IntegrationTestIntrakoreApps(IntegrationTestCase):
	"""How the INTRAKORE source fills Cargo Settings and what the Apps images it starts install."""

	def setUp(self):
		frappe.set_user("Administrator")
		frappe.db.savepoint("intrakore_test")
		self.addCleanup(frappe.db.rollback, save_point="intrakore_test")
		use_test_settings()
		frappe.db.set_single_value("Cargo Settings", "app_source", "Intrakore")
		set_encrypted_password("Cargo Settings", "Cargo Settings", TOKEN, "intrakore_github_token")
		frappe.clear_document_cache("Cargo Settings", "Cargo Settings")

	def sync(self, lock: str = LOCK, manifest: str | None = MANIFEST) -> list[str]:
		with patch(f"{INTRAKORE}.requests.get", side_effect=serve_repo_file) as get:
			changed = intrakore.sync_app_releases(lock, manifest)
		self.requests = get.call_args_list
		return changed

	def releases(self) -> list[tuple]:
		return [
			(row.app, row.install_order, row.branch, row.commit[:1], row.requires or "", row.version)
			for row in frappe.get_doc("Cargo Settings").intrakore_apps
		]

	def test_a_sync_fills_the_releases_from_the_lock_and_the_manifest(self):
		self.assertEqual(len(self.sync()), 4)

		self.assertEqual(
			self.releases(),
			[
				("intrakore_ui", 10, "main", "a", "", "aaaaaaa"),
				("intrakore_master", 30, "main", "b", "", "bbbbbbb"),
				("intrakore_estimation", 60, "main", "e", "intrakore_master\nintrakore_ui", "eeeeeee"),
				("intrakore_crm", 140, "develop", "c", "intrakore_master\nintrakore_ui", "1.4.0"),
			],
		)

	def test_a_sync_reads_github_with_the_token_at_the_locked_commit(self):
		self.sync()

		hooks = next(call for call in self.requests if call.args[0].endswith("intrakore_crm/hooks.py"))
		self.assertEqual(
			hooks.args[0],
			f"https://raw.githubusercontent.com/intrakore-lite/intrakore_crm/{'c' * 40}/intrakore_crm/hooks.py",
		)
		self.assertEqual(hooks.kwargs["headers"], {"Authorization": f"token {TOKEN}"})

	def test_the_token_is_not_sent_to_another_host(self):
		self.assertEqual(intrakore.github_headers("https://devops.intrakore.test/prod.lock"), {})

	def test_a_sync_reads_github_only_for_the_apps_that_moved(self):
		self.sync()

		moved = LOCK.replace("c" * 40, "d" * 40)
		self.assertEqual(self.sync(moved), ["intrakore_crm"])
		self.assertTrue(all("intrakore_crm" in call.args[0] for call in self.requests))

	def test_an_app_gone_from_the_lock_is_dropped(self):
		self.sync()
		self.sync("\n".join(line for line in LOCK.splitlines() if "intrakore_crm" not in line))

		self.assertNotIn("intrakore_crm", [release[0] for release in self.releases()])

	def test_a_sync_without_a_lock_or_its_url_is_refused(self):
		with self.assertRaises(frappe.ValidationError):
			intrakore.sync_app_releases()

	def test_a_bundle_installs_both_apps_after_what_they_require_in_manifest_order(self):
		self.sync()
		self.set_signup_app("intrakore_crm", also_installs="intrakore_estimation")

		self.assertEqual(
			[app.name for app in intrakore.get_install_order("intrakore_crm")],
			["intrakore_ui", "intrakore_master", "intrakore_estimation", "intrakore_crm"],
		)

	def test_an_app_requiring_an_app_with_no_release_cannot_install(self):
		self.sync("\n".join(line for line in LOCK.splitlines() if "intrakore_master" not in line))

		with self.assertRaisesRegex(frappe.ValidationError, "intrakore_master"):
			intrakore.get_install_order("intrakore_crm")

	def test_apps_that_require_each_other_cannot_install(self):
		self.sync()
		frappe.db.set_value("Intrakore App Release", {"app": "intrakore_master"}, "requires", "intrakore_crm")
		frappe.clear_document_cache("Cargo Settings", "Cargo Settings")

		with self.assertRaisesRegex(frappe.ValidationError, "require each other"):
			intrakore.get_install_order("intrakore_crm")

	def test_intrakore_releases_come_from_their_private_repositories(self):
		self.sync()

		release = intrakore.get_install_order("intrakore_crm")[-1]
		self.assertEqual(release.repo, "https://github.com/intrakore-lite/intrakore_crm.git")
		self.assertEqual(release.branch, "develop")
		self.assertFalse(release.prebuilt_assets)

	def set_signup_app(self, app: str, also_installs: str = "") -> None:
		set_signup_apps((app,))
		frappe.db.set_value(
			"Signup App", {"parentfield": "signup_apps", "app": app}, "also_installs", also_installs
		)

	def completed_site(self) -> PilotImage:
		with patch.object(PilotImage, "after_insert"):
			site = frappe.get_doc(
				{
					"doctype": "Pilot Image",
					"pilot_version": f"v0.0.96-{frappe.generate_hash(length=6)}",
					"frappe_branch": "version-16",
					"frappe_commit": FRAPPE_PIN,
					"image_type": "Site",
				}
			).insert()
		site.db_set({"status": "Completed", "frappe_version": "16.26.3"})
		return site

	def start_apps(self) -> list[str]:
		frappe.db.set_single_value("Cargo Settings", "track_pilot_releases", 1)
		with (
			patch(f"{CONTROLLER}.is_published", return_value=False) as is_published,
			patch.object(PilotImage, "after_insert"),
			patch.object(frappe.db, "commit"),
			patch.object(frappe.db, "rollback"),
		):
			started = start_apps_images()
		self.asked_for_assets = is_published.call_args_list
		return started

	def test_an_intrakore_apps_image_starts_without_prebuilt_assets(self):
		self.sync()
		self.set_signup_app("intrakore_crm", also_installs="intrakore_estimation")
		self.completed_site()

		started = self.start_apps()

		self.assertEqual(len(started), 1)
		self.assertEqual(self.asked_for_assets, [])
		install_order = intrakore.get_install_order("intrakore_crm")
		self.assertEqual(
			frappe.db.get_value("Pilot Image", started[0], "app_commit"),
			intrakore.get_release_set_id(install_order),
		)

	def test_an_intrakore_apps_image_waits_for_assets_when_asked_to(self):
		frappe.db.set_single_value("Cargo Settings", "build_without_prebuilt_assets", 0)
		self.sync()
		self.set_signup_app("intrakore_crm")
		self.completed_site()

		self.assertEqual(self.start_apps(), [])
		self.assertIn(
			"https://github.com/intrakore-lite/intrakore_ui/releases/download/assets-main/intrakore_ui-",
			self.asked_for_assets[0].args[0],
		)

	def test_a_move_of_any_app_in_the_install_set_starts_a_new_image(self):
		self.sync()
		self.set_signup_app("intrakore_crm", also_installs="intrakore_estimation")
		self.completed_site()
		self.assertEqual(len(self.start_apps()), 1)
		self.assertEqual(self.start_apps(), [])

		self.sync(LOCK.replace("e" * 40, "f" * 40))

		self.assertEqual(len(self.start_apps()), 1)

	def apps_image(self) -> PilotImage:
		self.sync()
		self.set_signup_app("intrakore_crm", also_installs="intrakore_estimation")
		self.completed_site()
		return frappe.get_doc("Pilot Image", self.start_apps()[0])

	def test_an_apps_image_pins_the_whole_install_set(self):
		image = self.apps_image()
		with patch(f"{CONTROLLER}.get_frappe_release", return_value="16.26.3"):
			image.pin_releases()

		self.assertEqual(
			image.get_provision_environment()["REQUIRED_APPS"].splitlines()[-1],
			f"intrakore_crm https://github.com/intrakore-lite/intrakore_crm.git develop {'c' * 40}",
		)

	def test_an_apps_image_whose_releases_moved_is_not_pinned(self):
		image = self.apps_image()
		self.sync(LOCK.replace("b" * 40, "9" * 40))

		with (
			patch(f"{CONTROLLER}.get_frappe_release", return_value="16.26.3"),
			self.assertRaisesRegex(frappe.ValidationError, "changed after this image started"),
		):
			image.pin_releases()

	def test_only_an_apps_build_gets_the_token(self):
		image = self.apps_image()
		self.assertEqual(image.get_provision_environment()["GIT_TOKEN"], TOKEN)

		image.image_type = "Site"
		self.assertNotIn("GIT_TOKEN", image.get_provision_environment())

	def test_a_marketplace_build_gets_no_token(self):
		image = self.apps_image()
		frappe.db.set_single_value("Cargo Settings", "app_source", "Marketplace")

		self.assertNotIn("GIT_TOKEN", image.get_provision_environment())

	def test_an_apps_image_sells_its_bundle_in_order_without_repeats(self):
		image = self.apps_image()
		frappe.db.set_value(
			"Signup App",
			{"parentfield": "signup_apps", "app": "intrakore_crm"},
			"also_installs",
			"intrakore_estimation, intrakore_crm intrakore_estimation",
		)

		self.assertEqual(
			json.loads(image.get_provision_environment()["SIDEBAR_APPS"]),
			["intrakore_crm", "intrakore_estimation"],
		)

	def test_a_signup_app_alone_sells_only_itself(self):
		self.sync()
		self.set_signup_app("intrakore_crm")

		self.assertEqual(intrakore.get_sidebar_apps("intrakore_crm"), ["intrakore_crm"])

	def test_a_bundle_with_a_bad_app_name_is_refused(self):
		self.sync()
		self.set_signup_app("intrakore_crm", also_installs="intrakore_estimation;reboot")

		with self.assertRaisesRegex(frappe.ValidationError, "not an app name"):
			intrakore.get_sidebar_apps("intrakore_crm")

	def test_only_an_intrakore_apps_build_sells_a_bundle(self):
		image = self.apps_image()
		self.assertIn("SIDEBAR_APPS", image.get_provision_environment())

		image.image_type = "Site"
		self.assertNotIn("SIDEBAR_APPS", image.get_provision_environment())

		image.image_type = "Apps"
		frappe.db.set_single_value("Cargo Settings", "app_source", "Marketplace")
		self.assertNotIn("SIDEBAR_APPS", image.get_provision_environment())


class IntegrationTestFrappePin(IntegrationTestCase):
	"""A Frappe branch pinned to a commit in Cargo Settings."""

	def setUp(self):
		frappe.set_user("Administrator")
		frappe.db.savepoint("frappe_pin_test")
		self.addCleanup(frappe.db.rollback, save_point="frappe_pin_test")
		use_test_settings()
		set_settings_rows("frappe_branches", "Frappe Branch", "branch", ("version-16",))
		frappe.db.set_value("Frappe Branch", {"branch": "version-16"}, "commit", FRAPPE_PIN)

	def test_a_pinned_branch_builds_its_commit_not_its_head(self):
		with patch(f"{CONTROLLER}.get_frappe_head_commit", return_value=COMMIT) as head:
			self.assertEqual(get_frappe_commit("version-16"), FRAPPE_PIN)

		head.assert_not_called()

	def test_an_unpinned_branch_follows_its_head(self):
		with patch(f"{CONTROLLER}.get_frappe_head_commit", return_value=COMMIT):
			self.assertEqual(get_frappe_commit("develop"), COMMIT)

	def base(self) -> dict[str, str]:
		return {
			"pilot_version": "v0.0.96-pre-alpha",
			"frappe_branch": "version-16",
			"frappe_commit": FRAPPE_PIN,
			"image_type": "Base",
		}

	def test_a_pinned_commit_waits_for_the_pilot_release_only(self):
		with patch(f"{CONTROLLER}.is_published", return_value=True) as is_published:
			self.assertTrue(has_prebuilt_assets(self.base()))

		self.assertEqual(
			[call.args[0] for call in is_published.call_args_list],
			["https://github.com/frappe/pilot/releases/download/v0.0.96-pre-alpha/pilot.tar.gz"],
		)

	def test_a_pinned_commit_waits_for_frappe_assets_when_asked_to(self):
		frappe.db.set_single_value("Cargo Settings", "build_without_prebuilt_assets", 0)

		with patch(f"{CONTROLLER}.is_published", return_value=True) as is_published:
			has_prebuilt_assets(self.base())

		self.assertEqual(len(is_published.call_args_list), 2)

	def test_release_tracking_starts_the_pinned_commit(self):
		frappe.db.set_single_value("Cargo Settings", "track_pilot_releases", 1)
		with (
			patch(f"{CONTROLLER}.get_latest_pilot_release", return_value="v0.0.96-pre-alpha"),
			patch(f"{CONTROLLER}.get_frappe_head_commit", return_value=COMMIT),
			patch(f"{CONTROLLER}.is_published", side_effect=lambda url: "frappe/frappe" not in url),
			patch.object(PilotImage, "after_insert"),
			patch.object(frappe.db, "commit"),
			patch.object(frappe.db, "rollback"),
		):
			started = start_base_images()

		self.assertEqual(
			[frappe.db.get_value("Pilot Image", name, "frappe_commit") for name in started], [FRAPPE_PIN]
		)
